#!/usr/bin/env node
/**
 * scripts/build-emoji-data.mjs — regenerates lib/agent/media/emoji-data-twemoji.ts from the Twemoji SVG set
 * (@twemoji/svg 15.0.0: `npm pack @twemoji/svg@15.0.0 && tar xzf twemoji-svg-15.0.0.tgz`).
 *
 *   node scripts/build-emoji-data.mjs <path to the package folder>
 *
 * Kept: every emoji WITHOUT a skin-tone modifier (U+1F3FB–U+1F3FF), keyed by its code points in hex joined with "-"
 * (Twemoji's own file names), each the SVG's inner markup on its 36×36 viewBox. The set is one JSON object, brotli'd and
 * base64'd into a TS module, so the server bundle always carries it (like the FiraGO font: no file tracing).
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { brotliCompressSync, constants } from 'node:zlib';

const dir = process.argv[2];
if (!dir) { console.error('usage: node scripts/build-emoji-data.mjs <@twemoji/svg package folder>'); process.exit(1); }
const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
const set = {};
for (const f of readdirSync(dir).filter((x) => x.endsWith('.svg')).sort()) {
  const key = f.slice(0, -4);
  if (!/^[0-9a-f]{2,6}(?:-[0-9a-f]{2,6})*$/.test(key) || /(?:^|-)1f3f[b-f](?:-|$)/.test(key)) continue;
  const svg = readFileSync(join(dir, f), 'utf8').trim();
  const m = /^<svg[^>]*viewBox="0 0 36 36"[^>]*>([\s\S]*)<\/svg>$/.exec(svg);
  if (!m) { console.error(`skipped ${f}: not a 36×36 Twemoji`); continue; }
  set[key] = m[1];
}
const json = Buffer.from(JSON.stringify(set), 'utf8');
const packed = brotliCompressSync(json, { params: { [constants.BROTLI_PARAM_QUALITY]: 11, [constants.BROTLI_PARAM_SIZE_HINT]: json.length } });
const b64 = packed.toString('base64');
const out = `// Twemoji ${pkg.version} (@twemoji/svg), every emoji without a skin-tone modifier: ${Object.keys(set).length} SVGs, keyed by their
// code points (Twemoji's file names), each the inner markup of its 36×36 viewBox. One JSON object, brotli + base64, so the
// server bundle always carries it. Generated by scripts/build-emoji-data.mjs: do not edit by hand.
//
// Twemoji graphics (c) Twitter, Inc and other contributors, licensed under CC-BY 4.0
// (https://creativecommons.org/licenses/by/4.0/); attribution: ./TWEMOJI-LICENSE.txt.

export const TWEMOJI_COUNT = ${Object.keys(set).length};
// One literal on one line: a long chain of "+" overflows a compiler's stack (SWC under jest segfaulted on it).
export const TWEMOJI_BR_B64 =
  '${b64}';
`;
const target = join(process.cwd(), 'lib/agent/media/emoji-data-twemoji.ts');
writeFileSync(target, out);
console.log(`${Object.keys(set).length} emoji, json ${json.length} B, brotli ${packed.length} B, module ${out.length} B → ${target}`);
