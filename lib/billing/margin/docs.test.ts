/** @jest-environment node */
/**
 * Phase 8.1: the finance docs are GENERATED from the engine, so no number in them is typed by hand.
 *   WRITE_FINANCE_DOCS=1 npx jest lib/billing/margin/docs.test.ts   → rewrites docs/v8.1-finance/{COGS_MATRIX.md,PACKAGES.md,pricing.v8.json}
 * Without the env var the test fails when a committed doc no longer matches the engine (a price moved, docs not regenerated).
 */
import fs from 'node:fs';
import path from 'node:path';
import { COGS, PRICES_READ_AT, fullCostUsd } from './cogs';
import { priceList } from './catalog';
import { MARGIN_ECON, creditsPerUsd, gelToUsd, netGelPerCredit } from './econ';
import { PLANS, TOPUPS, creditGelOf, whatYouGet } from './packages';

const DIR = path.join(process.cwd(), 'docs', 'v8.1-finance');
const pct = (m: number) => `${(m * 100).toFixed(1)} %`;
const usd = (n: number) => `$${n < 0.01 ? n.toFixed(5) : n < 1 ? n.toFixed(4) : n.toFixed(2)}`;

function cogsMatrix(): string {
  const list = priceList();
  const out: string[] = [
    '# Master COGS & Pricing Matrix (v8, 65 % gross margin, APPROVED by GG 2026-11-14)',
    '',
    `Generated by \`lib/billing/margin/docs.test.ts\` from the price engine. Google prices read ${PRICES_READ_AT.slice(0, 10)} from the public Vertex AI / Cloud TTS / Speech-to-Text pricing pages (full billed prices, not the 50 % promo). Do not edit by hand: run \`WRITE_FINANCE_DOCS=1 npx jest lib/billing/margin/docs.test.ts\`.`,
    '',
    '## The rule',
    '',
    '`price ₾ = cost ₾ ÷ (1 − 0.65)`, measured on what we KEEP from the cheapest credit we sell:',
    '',
    `- cost ₾ = Google USD × ${MARGIN_ECON.gelPerUsd} ₾/$ × (1 + ${MARGIN_ECON.fxReserve} FX reserve)`,
    `- net ₾ per credit = ${MARGIN_ECON.floorCreditGel} ₾ floor × (1 − ${MARGIN_ECON.cardFee} BOG card fee) ÷ (1 + ${MARGIN_ECON.vatRate} VAT) = ${netGelPerCredit(MARGIN_ECON.floorCreditGel).toFixed(4)} ₾`,
    `- credits = ⌈cost ₾ ÷ (0.35 × net ₾ per credit)⌉ → **${creditsPerUsd().toFixed(2)} credits per $1 of Google cost**`,
    '',
    'Every package sells a credit at ≥ the floor, so every action keeps ≥ 65 % whatever package paid for it. A top-up buyer at the 0.10 ₾ sticker gives us more (the "sticker" column).',
    '',
    '## Price list',
    '',
    '| Action | Model | Our cost | Credits (new) | Today | ₾ at 0.10 | $ | Margin floor | Margin sticker |',
    '|---|---|---:|---:|---:|---:|---:|---:|---:|',
  ];
  for (const r of list)
    out.push(
      `| ${r.label.en} (${r.unit.en}) \`${r.id}\` | ${r.model} | ${usd(r.costUsd)} | **${r.credits}** | ${r.current ?? '—'} | ${r.gel.toFixed(2)} | ${r.usd.toFixed(2)} | ${pct(r.marginFloor)} | ${pct(r.marginBase)} |`,
    );
  out.push('', '## Cost lines (sources)', '', '| Action | Line | USD | Kind | Source |', '|---|---|---:|---|---|');
  for (const a of COGS) {
    for (const l of a.lines) out.push(`| \`${a.id}\` | ${l.what} | ${usd(l.usd)} | ${l.source} | ${l.url} |`);
    out.push(`| \`${a.id}\` | retries ${pct(a.retryShare)} + hosting ${usd(a.infraUsd)} → **full cost** | **${usd(fullCostUsd(a))}** | | |`);
  }
  return out.join('\n') + '\n';
}

function packagesDoc(): string {
  const out: string[] = [
    '# Plans and top-ups (APPROVED by GG 2026-11-14)',
    '',
    'Generated from `lib/billing/margin/packages.ts`. Prices are in ₾ because BOG charges ₾ ($ at 2.7 ₾ for comparison). Approved by GG 2026-11-14 10:26Z. Sold once the wiring flag is on.',
    '',
    '## Monthly plans',
    '',
    '| Plan | ₾ / month | ≈ $ | Credits | ₾ per credit | 8 s video (720p) | Images (1K) | Songs | Avatar minutes | Read-aloud minutes |',
    '|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|',
  ];
  for (const p of PLANS) {
    const w = whatYouGet(p.credits);
    out.push(
      `| ${p.name.en}${p.highlight ? ' ★' : ''} | ${p.priceGel} | ${gelToUsd(p.priceGel).toFixed(2)} | ${p.credits} | ${p.priceGel ? creditGelOf(p).toFixed(4) : '—'} | ${w.videos8s720} | ${w.images1k} | ${w.songs} | ${w.avatarMinutes} | ${w.ttsMinutes} |`,
    );
  }
  out.push('', 'Each column is "OR": a plan buys that many of ONE thing, or any mix.', '', '## Top-ups (one time, never expire)', '', '| Pack | ₾ | Credits | Bonus | ₾ per credit |', '|---|---:|---:|---:|---:|');
  for (const t of TOPUPS) out.push(`| ${t.id} | ${t.priceGel} | ${t.credits} | ${t.bonusPct ? `+${t.bonusPct} %` : '—'} | ${creditGelOf(t).toFixed(4)} |`);
  out.push(
    '',
    '## Competitors (public pricing pages, read 2026-11-14)',
    '',
    '| Product | Plan | Price / month | What you get |',
    '|---|---|---:|---|',
    '| HeyGen | Creator / Pro / Business | $29 / $49 / $149 | 600 / 1,000 credits; avatar video (heygen.com/pricing) |',
    '| Midjourney | Basic / Standard / Pro / Mega | $10 / $30 / $60 / $120 | 3.3 / 15 / 30 / 60 h fast GPU; images + short video (docs.midjourney.com) |',
    '| ChatGPT | Go / Plus / Pro | $8 / $20 / from $100 | chat, images, Sora inside limits (chatgpt.com/pricing) |',
    '| Runway | Standard / Pro / Max | $15 / $35 / $95 | 625 / 2,250 credits; an 8 s Veo 3.1 clip with audio costs $4.98–$7.68 (runwayml.com/pricing) |',
    '| Suno | Pro / Premier | $10 / $30 | songs (suno.com/pricing) |',
    '',
    `MyAvatar Pro (${PLANS.find((p) => p.id === 'pro')!.priceGel} ₾ ≈ $${gelToUsd(PLANS.find((p) => p.id === 'pro')!.priceGel)}) sits between HeyGen Pro and Midjourney Pro, and one plan covers video, images, music, voice and a live avatar. An 8 s 720p Omni clip costs ✦${priceList().find((r) => r.id === 'video.omni.720p.8s')!.credits} (≈ $${priceList().find((r) => r.id === 'video.omni.720p.8s')!.usd}), under Runway's price for a comparable Veo clip.`,
  );
  return out.join('\n') + '\n';
}

function pricingJson(): string {
  const doc = {
    version: 'v8-proposal',
    pricesReadAt: PRICES_READ_AT,
    rule: { minGrossMargin: MARGIN_ECON.minGrossMargin, floorCreditGel: MARGIN_ECON.floorCreditGel, baseCreditGel: MARGIN_ECON.baseCreditGel, gelPerUsd: MARGIN_ECON.gelPerUsd, fxReserve: MARGIN_ECON.fxReserve, cardFee: MARGIN_ECON.cardFee, vatRate: MARGIN_ECON.vatRate, creditsPerUsd: Math.round(creditsPerUsd() * 1e4) / 1e4 },
    actions: priceList().map((r) => ({ id: r.id, service: r.service, model: r.model, costUsd: Math.round(r.costUsd * 1e5) / 1e5, credits: r.credits, current: r.current, gel: r.gel, usd: r.usd, marginFloor: Math.round(r.marginFloor * 1e4) / 1e4, marginBase: Math.round(r.marginBase * 1e4) / 1e4 })),
    plans: PLANS.map((p) => ({ id: p.id, priceGel: p.priceGel, credits: p.credits, cadence: p.cadence, rolloverMonths: p.rolloverMonths, whatYouGet: whatYouGet(p.credits) })),
    topups: TOPUPS.map((t) => ({ id: t.id, priceGel: t.priceGel, credits: t.credits, bonusPct: t.bonusPct })),
  };
  return JSON.stringify(doc, null, 2) + '\n';
}

const FILES: Record<string, () => string> = { 'COGS_MATRIX.md': cogsMatrix, 'PACKAGES.md': packagesDoc, 'pricing.v8.json': pricingJson };

describe('generated finance docs', () => {
  for (const [name, gen] of Object.entries(FILES)) {
    test(`${name} matches the engine`, () => {
      const file = path.join(DIR, name);
      if (process.env.WRITE_FINANCE_DOCS === '1') {
        fs.mkdirSync(DIR, { recursive: true });
        fs.writeFileSync(file, gen());
      }
      expect(fs.readFileSync(file, 'utf8')).toBe(gen());
    });
  }
});
